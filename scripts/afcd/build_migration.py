"""
Builds the SQL that loads the Australian Food Composition Database (AFCD)
into the `foods` table.

Usage:
  1. Download "AFCD Release 3 - Nutrient profiles.xlsx" from
     https://www.foodstandards.gov.au/science-data/food-nutrient-databases/afcd/australian-food-composition-database-download-excel-files
  2. python3 scripts/afcd/build_migration.py <path to Nutrient profiles.xlsx> <output .sql file>

Data: © Food Standards Australia New Zealand, AFCD Release 3,
licensed under CC BY-SA 3.0 AU (http://creativecommons.org/licenses/by-sa/3.0/au/deed.en).
Change made: energy converted from kJ to kcal (÷ 4.184); values rounded to 1 decimal place.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from xlsx_read import read_workbook, rows  # noqa: E402

SHEET = 'All solids & liquids per 100 g'
HEADER_ROW = 2

# Column headers we use (matched after removing line breaks and extra spaces).
COLUMNS = {
    'id': 'Public Food Key',
    'classification': 'Classification',
    'name': 'Food Name',
    'kj': 'Energy with dietary fibre, equated (kJ)',
    'protein': 'Protein (g)',
    'fat': 'Fat, total (g)',
    'fibre': 'Total dietary fibre (g)',
    'sugars': 'Total sugars (g)',
    'carbs': 'Available carbohydrate, with sugar alcohols (g)',
    'saturated': 'Total saturated fatty acids, equated (g)',
    'sodium': 'Sodium (Na) (mg)',
}


def clean(header):
    return ' '.join((header or '').split())


def number(value):
    try:
        return round(float(value), 1)
    except (TypeError, ValueError):
        return None


def sql_text(value):
    return "'" + value.replace("'", "''") + "'"


def sql_number(value, default='null'):
    return default if value is None else repr(value)


def main(xlsx_path, out_path):
    z, shared, sheets = read_workbook(xlsx_path)
    all_rows = list(rows(z, shared, sheets[SHEET]))
    header = [clean(h) for h in all_rows[HEADER_ROW]]
    index = {key: header.index(title) for key, title in COLUMNS.items()}

    values = []
    skipped = 0
    for row in all_rows[HEADER_ROW + 1:]:
        get = lambda key: row[index[key]] if index[key] < len(row) else None  # noqa: E731
        food_id, name, kj = get('id'), get('name'), number(get('kj'))
        if not food_id or not name or kj is None:
            skipped += 1
            continue
        kcal = round(kj / 4.184, 1)
        values.append(
            '(' + ', '.join([
                sql_text(food_id.strip()),
                sql_text(' '.join(name.split())),
                sql_text(str(get('classification') or '').strip()) if get('classification') else 'null',
                repr(kcal),
                sql_number(number(get('protein')), '0'),
                sql_number(number(get('carbs')), '0'),
                sql_number(number(get('fat')), '0'),
                sql_number(number(get('fibre'))),
                sql_number(number(get('sugars'))),
                sql_number(number(get('saturated'))),
                sql_number(number(get('sodium'))),
            ]) + ')'
        )

    with open(out_path, 'w') as out:
        out.write('-- AFCD Release 3 reference foods (generated by scripts/afcd/build_migration.py).\n')
        out.write('-- © Food Standards Australia New Zealand. Licensed under CC BY-SA 3.0 AU:\n')
        out.write('-- http://creativecommons.org/licenses/by-sa/3.0/au/deed.en\n')
        out.write('-- Changes: energy converted from kJ to kcal; values rounded to 1 decimal place.\n\n')
        out.write('insert into public.foods (id, name, classification, kcal_100g, protein_100g, carbs_100g, '
                  'fat_100g, fibre_100g, sugars_100g, saturated_fat_100g, sodium_mg_100g) values\n')
        out.write(',\n'.join(values))
        out.write('\non conflict (id) do update set\n')
        out.write('  name = excluded.name, classification = excluded.classification, '
                  'kcal_100g = excluded.kcal_100g, protein_100g = excluded.protein_100g, '
                  'carbs_100g = excluded.carbs_100g, fat_100g = excluded.fat_100g, '
                  'fibre_100g = excluded.fibre_100g, sugars_100g = excluded.sugars_100g, '
                  'saturated_fat_100g = excluded.saturated_fat_100g, '
                  'sodium_mg_100g = excluded.sodium_mg_100g;\n')
    print(f'Wrote {len(values)} foods to {out_path} (skipped {skipped} without energy data).')


if __name__ == '__main__':
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
